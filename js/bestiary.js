// Очки знания о монстре из записи бестиария.
export function knowledge(rec, maxRoom) {
  if (!rec) return 0;
  return Math.max(0, maxRoom - rec.first) + (rec.runs || 0) + Math.floor((rec.kills || 0) / 3);
}
