export function actOf(room) { return ACTS[Math.min(ACTS.length - 1, Math.floor((room - 1) / 100))]; }

export function placeOf(room) {
  const act = actOf(room);
  let p = act.places[0];
  for (const q of act.places) if (room >= q[0]) p = q;
  return { name: p[1], tint: p[2], exits: p[3] || ['door'] };
}

// Какие враги уже открыты к комнате room и с каким весом.
// Новичок первые 8 комнат после открытия попадается втрое чаще, чтобы его точно встретили.
export function enemyWeights(room) {
  const w = {};
  for (const [k, d] of Object.entries(ENEMY)) {
    if (room < d.unlock) continue;
    const fresh = room - d.unlock < 8 ? 3 : 1;
    w[k] = d.weight * fresh;
  }
  return w;
}

// Враги, которые впервые появляются в этой комнате (для надписи в начале).
export function newEnemies(room) {
  return Object.entries(ENEMY).filter(([, d]) => d.unlock === room || d.unlock === room - 1).map(([, d]) => d.name);
}

// Параметры комнаты: чем дальше, тем быстрее, плотнее и разнообразнее.
export function roomLevel(room, diffKey) {
  const D = DIFFICULTY[diffKey] || DIFFICULTY.normal;
  const a = Math.floor((room - 1) / 100);          // 0..3 — номер акта
  const t = ((room - 1) % 100) / 99;              // 0..1 — прогресс внутри акта
  const obstacles = enemyWeights(room);
  const place = placeOf(room);
  const boss = room % 100 === 0;
  const gapK = Math.max(0.5, (1 - t * 0.35 - a * 0.035)) * D.gap;
  // длительность растёт по всей игре: 1 минута в первой комнате → 5 минут к 400-й
  const secs = Math.round(60 + 240 * (room - 1) / (ROOMS_TOTAL - 1));
  const speed = (390 + a * 28 + t * 170) * D.speed;
  const length = Math.round(secs * speed * 1.12 / PX_PER_METER);
  // флажки сохранения на лёгком: делят комнату на равные куски (примерно каждые 45 с)
  const parts = Math.max(2, Math.round(secs / 45));
  // каким путём уходим из комнаты: дверь, лестница, лифт, потайной шкаф (зависит от места)
  const hx = Math.sin(room * 91.7 + 3.1) * 43758.5453;
  const exit = boss || room === ROOMS_TOTAL ? 'door' : place.exits[Math.floor((hx - Math.floor(hx)) * place.exits.length)];
  const checkpoints = D.checkpoints ? Array.from({ length: parts - 1 }, (_, i) => Math.round(length * (i + 1) / parts)) : [];
  return {
    kind: 'room', room, act: a + 1, diff: diffKey,
    name: `Комната ${room}`, place: place.name,
    length: boss ? Infinity : length,   // в метрах
    seconds: secs,
    speed,
    speedGrowth: speed * 0.22 / (length / 10),   // к концу комнаты скорость вырастает на ~22%
    checkpoints: boss ? [] : checkpoints,
    special: boss ? null : specialRoom(room),
    fresh: newEnemies(room),
    gap: [1.05 * gapK, 1.5 * gapK],
    combo: Math.min(0.8, D.combo + t * 0.12 + a * 0.045),
    enemy: D.enemy * (1 + a * 0.04),
    obstacles,
    hintAll: !!D.hints,
    nightmare: !!D.nightmare,
    palette: { wallTint: place.tint },
    findChance: 0.1 * D.find * (1 + a * 0.15),
    boss: boss ? { name: ACTS[a].boss, hp: Math.round((16 + a * 4) * D.boss), act: a + 1 } : null,
    exit,
    // после 400-й — дверь «ВХОД» (первый этаж был замком), последняя дверь игры — без таблички
    doorLabel: room === 400 ? 'ВХОД' : room === ROOMS_TOTAL ? '' : EXITS[exit].label,
  };
}

// Особые комнаты вместо бега: поиск предметов в середине каждого акта (50, 150, 250, 350)
// и редкие (2%) головоломки — «три в ряд» или «пятнашки» с портретом.
export function specialRoom(room) {
  if (room % 100 === 50) return 'search';
  const h = Math.sin(room * 12.9898 + 78.233) * 43758.5453;
  const r = h - Math.floor(h);
  if (room > 5 && r < 0.02) return room % 2 ? 'match3' : 'puzzle';
  return null;
}

// Бесконечный забег: «Коридор Вечного Сквозняка».
export function endlessLevel(diffKey, maxRoom = 0) {
  const D = DIFFICULTY[diffKey] || DIFFICULTY.normal;
  // в бесконечном забеге — все враги, которых игрок уже встречал в комнатах (но не меньше первых шести)
  const obstacles = enemyWeights(Math.max(24, maxRoom + 1));
  return {
    kind: 'endless', room: 0, act: 0, diff: diffKey,
    name: 'Коридор Вечного Сквозняка', place: 'бесконечный забег',
    length: Infinity,
    speed: 430 * D.speed, speedGrowth: 6,
    gap: [1.1 * D.gap, 1.55 * D.gap],
    combo: D.combo, comboGrowth: true, ramp: true,   // 3D: начинаем с простого, сложность растёт с метрами
    enemy: D.enemy,
    obstacles, hintAll: !!D.hints, nightmare: !!D.nightmare,
    palette: { wallTint: { gray: 0.5, mul: [0.86, 0.84, 0.98] } },
    findChance: 0.12 * D.find,   // проверяется каждые 400 м
    boss: null, doorLabel: 'ВЫХОД',
  };
}

