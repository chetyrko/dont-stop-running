// Карточка после комнаты room. met — какие враги попались в этом забеге, seen — уже показанные записки.
export function storyAfter(room, met = new Set(), seen = new Set()) {
  const pack = (s, key) => ({ kind: s[0], label: K[s[0]], text: s[1], key });
  if (BEATS[room]) return pack(BEATS[room], 'beat' + room);
  // враг, впервые встреченный — в порядке открытия
  for (const [type, d] of Object.entries(ENEMY).sort((a, b) => a[1].unlock - b[1].unlock)) {
    if (met.has(type) && ENEMY_LORE[type] && !seen.has('enemy:' + type)) return pack(ENEMY_LORE[type], 'enemy:' + type);
  }
  const place = placeOf(room).name;
  const pl = PLACE_LORE[place] || [];
  for (let i = 0; i < pl.length; i++) if (!seen.has(`place:${place}:${i}`)) return pack(pl[i], `place:${place}:${i}`);
  const pool = POOL[Math.min(3, Math.floor((room - 1) / 100))];
  return pack(pool[(room * 7) % pool.length], null);
}

