// Карточка после прохождения комнаты room.
export function storyAfter(room) {
  const s = STORY[room] || POOL[Math.min(3, Math.floor((room - 1) / 100))][(room * 7) % 12];
  return { kind: s[0], label: K[s[0]], text: s[1] };
}
